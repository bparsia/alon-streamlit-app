"""
Render the translation-table IR (build_ir.py's output) to LaTeX.

Six compact tables, nothing else -- no worked examples, no source-code
listings, no appendix:

Table 1: the four semantic components of an ALOn model (succ/act/nu) plus
the opposing relation from the action structure it's defined over,
alongside their concrete .mmd syntax (syntax reference only).
Table 2: the paper's own formula-primitive grammar (p, do(a,i), phi&phi,
~phi, Xphi, []phi) alongside its concrete ASCII syntax (syntax reference
only).
Table 3/4: structural/formula rows translated to OWL and SPARQL, paired
together -- SPARQL queries the same OWL ontology's ABox/structural-TBox
rather than deriving a separate translation, so they're the natural
DL-reasoner pairing (see render_structural_dl_table's docstring).
Table 5/6: structural/formula rows translated to pyDatalog, kept
SEPARATE from Tables 3/4 -- pyDatalog is a genuinely different reasoning
paradigm (rule-based, its own negation/closure semantics), not a third
parallel column alongside OWL/SPARQL.

Uses plain tabular with p{} fixed-width columns, NOT tabularx's X
columns -- X columns showed a real, reproducible bug when a short row
directly follows a tall/multi-line row (column separators computed
wrong, cells visually merge with zero space between them; confirmed by
isolating the exact same row alone vs. after a taller row). No extra
LaTeX package required beyond what a normal article/eptcs preamble
already has.

Usage:
  python -m tools.translation_table.render_latex [-o OUTPUT.tex]
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

IR_PATH = Path(__file__).parent / "translation_table.json"


def _break_camel_case(identifier: str) -> str:
    """Insert \\- at camelCase word boundaries so long OWL/Java-style
    identifiers (FunctionalObjectProperty, ObjectExactCardinality, ...)
    can wrap inside a narrow tabularx X column -- without this, LaTeX
    treats them as one unbreakable token and they overflow into the
    NEXT column rather than wrapping (confirmed via Overfull \\hbox
    warnings + visual column-overlap, not assumed)."""
    return re.sub(r'(?<=[a-z])(?=[A-Z])', r'\\-', identifier)


def _add_texttt_breakpoints(tex: str) -> str:
    """Post-process the fully-assembled .tex text, finding every
    \\texttt{...} span and inserting camelCase break points inside it.
    Applied once at the end rather than scattered through every
    string-building call site."""
    def repl(m):
        return r"\texttt{" + _break_camel_case(m.group(1)) + "}"
    return re.sub(r'\\texttt\{([^{}]*)\}', repl, tex)


def _tex_escape(text: str) -> str:
    """Escape plain prose/identifiers for direct LaTeX interpolation.
    Backslash must be escaped FIRST -- every other substitution inserts
    a literal backslash, and escaping backslash after those would
    double-escape them."""
    return (text.replace("\\", r"\textbackslash{}")
                .replace("{", r"\{")
                .replace("}", r"\}")
                .replace("&", r"\&")
                .replace("_", r"\_")
                .replace("%", r"\%")
                .replace("#", r"\#")
                .replace("<", r"\textless{}")
                .replace(">", r"\textgreater{}"))


_GENERATED_HEADER = (
    r"% Auto-generated by tools/translation_table/render_latex.py -- do not edit by hand." "\n"
    r"% Regenerate via: python -m tools.translation_table.build_ir && python -m tools.translation_table.render_latex"
)

# p{} fixed-width columns everywhere below, not tabularx's X columns: X
# columns showed a real, reproducible bug here -- a short row directly
# following a tall/multi-line row gets its column separators computed
# wrong (columns visually merge with zero space between them), confirmed
# by isolating the exact same row alone (correct) vs. after a taller row
# (broken). p{} avoids the X-column width algorithm entirely. Widths
# sized against the real measured \textwidth for eptcs.cls (455.24pt =
# 16.0cm).


def render_structural_syntax_table(ir: dict) -> str:
    """Table 1: Denotes + .mmd syntax only, no OWL/Datalog -- a syntax
    reference, not a translation table."""
    lines = [
        _GENERATED_HEADER,
        r"\begin{table}[h]",
        r"\centering",
        r"\caption{The semantic components of an \alon model "
        r"$\mathcal{M} = (\mathcal{DBT}, act, \nu)$, plus the opposing relation "
        r"from the action structure $\mathcal{A}=(A,n,\rhd)$, and their concrete \texttt{.mmd} syntax}",
        r"\begin{tabular}{l p{9cm}}",
        r"\hline",
        r"Denotes & \texttt{.mmd} syntax \\",
        r"\hline",
    ]
    for row in ir["structural"]:
        # Collapse multi-line concrete syntax (e.g. the YAML opposings:
        # block) to one line -- plain tabular cells don't wrap/break lines.
        single_line = " ".join(row["concrete_syntax"].split())
        concrete = r"\texttt{" + _tex_escape(single_line) + "}"
        lines.append(f"{row['math']} & {concrete} \\\\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def render_primitives_syntax_table(ir: dict) -> str:
    """Table 2: math notation + ASCII formula syntax only, no OWL/Datalog."""
    lines = [
        _GENERATED_HEADER,
        r"\begin{table}[h]",
        r"\centering",
        r"\caption{\alon's formula grammar "
        r"($\phi ::= p \mid do(a,i) \mid a\rhd b \mid \phi\wedge\phi \mid \neg\phi \mid X\phi \mid \Box\phi$, "
        r"minus $\rhd$ -- see Table 1's \emph{opposing} row) and its concrete ASCII syntax}",
        r"\begin{tabular}{l l}",
        r"\hline",
        r"ALOn & ASCII syntax \\",
        r"\hline",
    ]
    for row in ir["primitives"]:
        ascii_cell = row["ascii_syntax"]
        lines.append(f"{row['alon_syntax']} & {ascii_cell} \\\\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def render_structural_dl_table(ir: dict) -> str:
    """Table 3: .mmd syntax | OWL | SPARQL.

    OWL and SPARQL are grouped together (not with pyDatalog, see Table 5)
    because they're the same DL-reasoner-facing pairing: SPARQL queries
    the identical OWL ontology's ABox/structural-TBox
    (OWLSerializer.serialize_structural_only(), see
    docs/sparql_serializer.md) rather than deriving its own separate
    structural translation -- pyDatalog is a genuinely different
    reasoning paradigm (rule-based, its own closure semantics), not a
    third parallel column here.
    """
    lines = [
        _GENERATED_HEADER,
        r"\begin{table}[h]",
        r"\centering",
        r"\caption{Model structure translated to OWL and SPARQL (see Table 1 for what each row denotes; see Table 5 for pyDatalog)}",
        r"\begin{tabular}{p{3.2cm} p{3.6cm} p{3.6cm}}",
        r"\hline",
        r"\texttt{.mmd} syntax & OWL & SPARQL \\",
        r"\hline",
    ]
    for row in ir["structural"]:
        single_line = " ".join(row["concrete_syntax"].split())
        concrete = r"\texttt{" + _tex_escape(single_line) + "}"
        lines.append(f"{concrete} & {row['owl_rendering']} & {row['sparql_rendering']} \\\\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def render_primitives_dl_table(ir: dict) -> str:
    """Table 4: ASCII syntax | OWL | SPARQL."""
    lines = [
        _GENERATED_HEADER,
        r"\begin{table}[h]",
        r"\centering",
        r"\caption{\alon's formula grammar translated to OWL and SPARQL (see Table 2 for the math notation each row denotes; see Table 6 for pyDatalog)}",
        r"\begin{tabular}{l p{5.5cm} p{5.5cm}}",
        r"\hline",
        r"ASCII syntax & OWL & SPARQL \\",
        r"\hline",
    ]
    for row in ir["primitives"]:
        ascii_cell = row["ascii_syntax"]
        owl = row["owl"]["rendering"]
        sparql = row["sparql"]["rendering"]
        lines.append(f"{ascii_cell} & {owl} & {sparql} \\\\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def render_structural_datalog_table(ir: dict) -> str:
    """Table 5: .mmd syntax | pyDatalog, on its own -- see
    render_structural_dl_table's docstring for why pyDatalog isn't a
    third column alongside OWL/SPARQL."""
    lines = [
        _GENERATED_HEADER,
        r"\begin{table}[h]",
        r"\centering",
        r"\caption{Model structure translated to pyDatalog (see Table 1 for what each row denotes; see Table 3 for OWL/SPARQL)}",
        r"\begin{tabular}{p{4cm} p{8cm}}",
        r"\hline",
        r"\texttt{.mmd} syntax & pyDatalog \\",
        r"\hline",
    ]
    for row in ir["structural"]:
        single_line = " ".join(row["concrete_syntax"].split())
        concrete = r"\texttt{" + _tex_escape(single_line) + "}"
        lines.append(f"{concrete} & {row['datalog_rendering']} \\\\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def render_primitives_datalog_table(ir: dict) -> str:
    """Table 6: ASCII syntax | pyDatalog."""
    lines = [
        _GENERATED_HEADER,
        r"\begin{table}[h]",
        r"\centering",
        r"\caption{\alon's formula grammar translated to pyDatalog (see Table 2 for the math notation each row denotes; see Table 4 for OWL/SPARQL)}",
        r"\begin{tabular}{l p{10cm}}",
        r"\hline",
        r"ASCII syntax & pyDatalog \\",
        r"\hline",
    ]
    for row in ir["primitives"]:
        ascii_cell = row["ascii_syntax"]
        datalog = row["datalog"]["rendering"]
        lines.append(f"{ascii_cell} & {datalog} \\\\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("-o", "--output", type=Path, default=None)
    args = parser.parse_args()

    if not IR_PATH.exists():
        print(f"No IR found at {IR_PATH} -- run: python -m tools.translation_table.build_ir", file=sys.stderr)
        sys.exit(1)
    ir = json.loads(IR_PATH.read_text())

    # Structural before formula throughout; DL-reasoner (OWL+SPARQL)
    # tables before the separate pyDatalog tables -- see
    # render_structural_dl_table's docstring for why pyDatalog is split
    # out rather than a third parallel column.
    tables = [
        render_structural_syntax_table(ir),
        render_primitives_syntax_table(ir),
        render_structural_dl_table(ir),
        render_primitives_dl_table(ir),
        render_structural_datalog_table(ir),
        render_primitives_datalog_table(ir),
    ]
    output = "\n\n".join(tables)
    output = _add_texttt_breakpoints(output)

    output_path = args.output or (Path(__file__).parent / "translation_table.tex")
    output_path.write_text(output)
    print(f"Wrote {output_path}")


if __name__ == "__main__":
    main()
