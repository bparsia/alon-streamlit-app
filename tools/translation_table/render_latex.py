"""
Render the translation-table IR (build_ir.py's output) to LaTeX.

Two tables: primitives (ALOn syntax / OWL rendering / Datalog rendering,
using renderings.py's hand-polished notation) and structural (category /
notes / real code-extracted example, via a longtable since examples are
multi-line).

Code listings from the IR (raw Python source) are NOT included in the
LaTeX output by default -- they're the auditable ground truth backing
the polished renderings, meant for verifying the table stays honest, not
for direct inclusion in a paper. Pass --with-source to append them as a
separate appendix-style listing section if wanted.

Usage:
  python -m tools.translation_table.render_latex [--with-source] [-o OUTPUT.tex]
"""

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

IR_PATH = Path(__file__).parent / "translation_table.json"


def _tex_escape_verbatim(text: str) -> str:
    """Escape for use inside a verbatim-ish \\texttt block -- minimal,
    since example content is already XML/Datalog syntax with its own
    special characters (&, _, etc.)."""
    return (text.replace("\\", r"\textbackslash{}")
                .replace("&", r"\&")
                .replace("_", r"\_")
                .replace("%", r"\%")
                .replace("#", r"\#"))


def render_primitives_table(ir: dict) -> str:
    lines = [
        r"% Auto-generated by tools/translation_table/render_latex.py -- do not edit by hand.",
        r"% Regenerate via: python -m tools.translation_table.build_ir && python -m tools.translation_table.render_latex",
        r"\begin{table}[h]",
        r"\centering",
        r"\caption{ALOn primitive-operator translation to OWL and pyDatalog}",
        r"\begin{tabular}{l p{4.2cm} p{4.2cm}}",
        r"\hline",
        r"ALOn & OWL & pyDatalog \\",
        r"\hline",
    ]
    for row in ir["primitives"]:
        owl = row["owl"]["rendering"]
        datalog = row["datalog"]["rendering"]
        lines.append(f"{row['alon_syntax']} & {owl} & {datalog} \\\\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def render_structural_table(ir: dict) -> str:
    lines = [
        r"% Auto-generated by tools/translation_table/render_latex.py -- do not edit by hand.",
        r"\begin{table}[h]",
        r"\centering",
        r"\caption{Model-structure translation to OWL and pyDatalog (example: "
        + _tex_escape_verbatim(ir["canonical_model"]) + r")}",
        r"\begin{tabularx}{\textwidth}{l X}",
        r"\hline",
        r"Category & Notes \\",
        r"\hline",
    ]
    for row in ir["structural"]:
        lines.append(f"\\texttt{{{_tex_escape_verbatim(row['category'])}}} & {_tex_escape_verbatim(row['notes'])} \\\\")
    lines += [r"\hline", r"\end{tabularx}", r"\end{table}", ""]

    lines.append(r"% Real generated-output examples, one subsection per structural category.")
    for row in ir["structural"]:
        lines.append(f"\\subsubsection*{{{_tex_escape_verbatim(row['category'])}}}")
        lines.append(_tex_escape_verbatim(row["notes"]))
        lines.append("")
        if row["owl_example"]:
            lines.append(r"\paragraph{OWL example}")
            lines.append(r"\begin{verbatim}")
            lines.append(row["owl_example"])
            lines.append(r"\end{verbatim}")
        if row["datalog_example"]:
            lines.append(r"\paragraph{pyDatalog example}")
            lines.append(r"\begin{verbatim}")
            lines.append(row["datalog_example"])
            lines.append(r"\end{verbatim}")
        lines.append("")
    return "\n".join(lines)


def render_source_appendix(ir: dict) -> str:
    lines = [r"\section*{Appendix: extracted source (ground truth for the primitives table)}"]
    for row in ir["primitives"]:
        lines.append(f"\\subsubsection*{{{_tex_escape_verbatim(row['method_name'])}}}")
        lines.append(f"\\paragraph{{OWL}} ({_tex_escape_verbatim(row['owl']['source_file'])}:{row['owl']['source_line']})")
        lines.append(r"\begin{verbatim}")
        lines.append(row["owl"]["source"])
        lines.append(r"\end{verbatim}")
        lines.append(f"\\paragraph{{Datalog}} ({_tex_escape_verbatim(row['datalog']['source_file'])}:{row['datalog']['source_line']})")
        lines.append(r"\begin{verbatim}")
        lines.append(row["datalog"]["source"])
        lines.append(r"\end{verbatim}")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--with-source", action="store_true")
    parser.add_argument("-o", "--output", type=Path, default=None)
    args = parser.parse_args()

    if not IR_PATH.exists():
        print(f"No IR found at {IR_PATH} -- run: python -m tools.translation_table.build_ir", file=sys.stderr)
        sys.exit(1)
    ir = json.loads(IR_PATH.read_text())

    parts = [render_primitives_table(ir), render_structural_table(ir)]
    if args.with_source:
        parts.append(render_source_appendix(ir))
    output = "\n\n".join(parts)

    output_path = args.output or (Path(__file__).parent / "translation_table.tex")
    output_path.write_text(output)
    print(f"Wrote {output_path}")


if __name__ == "__main__":
    main()
